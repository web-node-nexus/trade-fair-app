import { useCallback, useEffect, useState } from "react";
import { ActivityIndicator, Alert, Linking, Platform, Share, StyleSheet, Text, View } from "react-native";
import * as FileSystem from "expo-file-system";
import * as Sharing from "expo-sharing";
import { useLocalSearchParams } from "expo-router";
import { QrPassView } from "@/components/tickets/QrPassView";
import { PrimaryButton } from "@/components/ui/PrimaryButton";
import { ScreenShell } from "@/components/ui/ScreenShell";
import { apiJson } from "@/lib/authFetch";
import type { VisitorTicket } from "@/api/types";
import { cardShadow } from "@/theme/cardShadow";
import { colors } from "@/theme/colors";
import { radius, spacing } from "@/theme/spacing";

export function TicketPassScreen() {
  const { ticketId } = useLocalSearchParams<{ ticketId: string }>();
  const [ticket, setTicket] = useState<VisitorTicket | null>(null);
  const [loading, setLoading] = useState(true);
  const [sharing, setSharing] = useState(false);

  const load = useCallback(async () => {
    const data = await apiJson<{ tickets: VisitorTicket[] }>("/visitor/tickets");
    const found = data.tickets?.find((t) => t.id === ticketId) ?? null;
    setTicket(found);
  }, [ticketId]);

  useEffect(() => {
    void load().finally(() => setLoading(false));
  }, [load]);

  const shareMessage = ticket
    ? `Trade Fair Wala gate pass\nEvent: ${ticket.eventTitle}\nTicket: ${ticket.id}\nType: ${ticket.ticketTypeName ?? "Visitor"}\nStatus: ${ticket.status}`
    : "";

  async function shareWhatsApp() {
    if (!ticket) return;
    const text = encodeURIComponent(`${shareMessage}\nQR: ${ticket.qrPayload}`);
    const url = Platform.OS === "ios" ? `whatsapp://send?text=${text}` : `whatsapp://send?text=${text}`;
    const can = await Linking.canOpenURL(url);
    if (can) await Linking.openURL(url);
    else Alert.alert("WhatsApp", "WhatsApp is not installed on this device.");
  }

  async function sharePdf() {
    if (!ticket) return;
    setSharing(true);
    try {
      const html = `<!DOCTYPE html><html><head><meta charset="utf-8"><title>Gate Pass - ${ticket.eventTitle}</title><style>body{font-family:system-ui,sans-serif;padding:32px;max-width:480px;margin:0 auto}h1{font-size:22px}code{display:block;padding:12px;background:#f4f4f5;border-radius:8px;word-break:break-all;font-size:12px;margin-top:16px}</style></head><body><h1>${ticket.eventTitle}</h1><p><strong>${ticket.ticketTypeName ?? "Visitor"}</strong> · ${ticket.status}</p><p>Ticket ID: ${ticket.id}</p><p>QR payload (show in app or scan):</p><code>${ticket.qrPayload}</code><p style="color:#666;font-size:12px;margin-top:24px">Generated by Trade Fair Wala</p></body></html>`;
      const htmlPath = `${FileSystem.cacheDirectory}pass-${ticket.id}.html`;
      await FileSystem.writeAsStringAsync(htmlPath, html);
      if (await Sharing.isAvailableAsync()) {
        await Sharing.shareAsync(htmlPath, {
          mimeType: "text/html",
          dialogTitle: "Share gate pass",
          UTI: "public.html",
        });
      } else {
        await Share.share({ message: shareMessage });
      }
    } catch (e) {
      Alert.alert("Share failed", e instanceof Error ? e.message : "Could not export pass");
    } finally {
      setSharing(false);
    }
  }

  if (loading) {
    return (
      <View style={styles.center}>
        <ActivityIndicator color={colors.emerald} size="large" />
      </View>
    );
  }

  if (!ticket?.qrPayload) {
    return (
      <ScreenShell title="Pass">
        <Text style={styles.muted}>Pass not found or QR unavailable.</Text>
      </ScreenShell>
    );
  }

  return (
    <ScreenShell title="Gate pass" subtitle={ticket.eventTitle} scroll onRefresh={load}>
      <QrPassView
        payload={ticket.qrPayload}
        title={ticket.eventTitle}
        subtitle={`${ticket.ticketTypeName ?? "Visitor"} · ${ticket.status}`}
      />
      <View style={styles.actionsCard}>
        <PrimaryButton
          label="Share on WhatsApp"
          variant="cta"
          onPress={() => void shareWhatsApp()}
        />
        <PrimaryButton
          label={sharing ? "Preparing…" : "Print / share pass"}
          variant="outline"
          style={{ marginTop: spacing.md }}
          disabled={sharing}
          onPress={() => void sharePdf()}
        />
        <PrimaryButton
          label="Share pass details"
          variant="outline"
          style={{ marginTop: spacing.md }}
          onPress={() => void Share.share({ message: `${shareMessage}\nQR: ${ticket.qrPayload}` })}
        />
      </View>
    </ScreenShell>
  );
}

const styles = StyleSheet.create({
  center: { flex: 1, alignItems: "center", justifyContent: "center", backgroundColor: colors.background },
  muted: { color: colors.textMuted, fontSize: 14 },
  actionsCard: {
    marginTop: spacing.xl,
    backgroundColor: colors.surface,
    borderRadius: radius.lg + 2,
    padding: spacing.lg,
    borderWidth: StyleSheet.hairlineWidth,
    borderColor: "rgba(10,31,61,0.06)",
    ...cardShadow,
  },
});
